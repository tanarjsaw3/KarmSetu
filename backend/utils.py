        f"SEVERITY LEVEL     : CRITICAL FINANCIAL DISCREPANCY",
        "-" * 80,
        "1. WORKER & IDENTITY REFERENCE",
        "-" * 80,
        f"Worker Full Name   : {worker_name}",
        f"Worker ID Hash     : {worker_id_hash}",
        f"Primary Trade      : {trade}",
        "",
        "-" * 80,
        "2. LOCKED CONTRACT TERMS (TAMPER-PROOF LEDGER)",
        "-" * 80,
        f"Contract ID        : #{contract_id}",
        f"Locked SHA-256 Hash: {contract_hash}",
        f"Agreed Daily Rate  : INR {daily_wage_rate:,.2f} / day",
        f"Contracted Duration: {duration_days} days",
        f"Designated Site    : {site_location}",
        "",
        "-" * 80,
        "3. FINANCIAL RECONCILIATION & DEFICIT AUDIT",
        "-" * 80,
        f"Verified Workdays  : {verified_workdays} days (100% Biometric & Geofence Validated)",
        f"Total Expected Wage: INR {expected_amount:,.2f} ({verified_workdays} days @ INR {daily_wage_rate:,.2f}/day)",
        f"Actual Disbursed   : INR {received_amount:,.2f}",
        " " + "-" * 78,
        f" >> UNDERPAYMENT DEFICIT : INR {deficit:,.2f} ({percentage_deficit:.2f}% OF EARNED WAGES WITHHELD)",
