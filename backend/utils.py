import math
import re
from datetime import datetime, timezone
from typing import Optional, Tuple, List


def haversine_distance(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """
    Calculate the great-circle distance between two points on the Earth
    in meters using the Haversine formula.
    """
    R = 6371000.0  # Earth radius in meters

    phi1 = math.radians(lat1)
    phi2 = math.radians(lat2)
    delta_phi = math.radians(lat2 - lat1)
    delta_lambda = math.radians(lon2 - lon1)

    a = math.sin(delta_phi / 2.0) ** 2 + \
        math.cos(phi1) * math.cos(phi2) * math.sin(delta_lambda / 2.0) ** 2
    c = 2.0 * math.atan2(math.sqrt(a), math.sqrt(1.0 - a))

    return R * c


def extract_site_coordinates(site_location: str, contract_lat: Optional[float] = None, contract_lon: Optional[float] = None) -> Optional[Tuple[float, float]]:
    """
    Extracts latitude and longitude from contract fields or from the site_location string.
    Supports formats like:
      - Direct float values from contract
      - "19.0760, 72.8777"
      - "Site Mumbai (19.0760, 72.8777)"
      - "lat: 19.0760, lon: 72.8777"
    """
    if contract_lat is not None and contract_lon is not None:
        return (contract_lat, contract_lon)

    if not site_location:
        return None

    # Regex search for two decimal numbers separated by comma or whitespace
    match = re.search(r"(-?\d+\.\d+)\s*,\s*(-?\d+\.\d+)", site_location)
    if match:
        try:
            lat = float(match.group(1))
            lon = float(match.group(2))
            if -90 <= lat <= 90 and -180 <= lon <= 180:
                return (lat, lon)
        except ValueError:
            pass

    return None


